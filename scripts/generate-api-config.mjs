// Writes src/app/config/api-url.generated.ts from API_URL before `ng build` / `ng serve`.
// Builds swap src/app/config/api-url.ts for it (fileReplacements in angular.json).
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const DEFAULT_API_URL = 'http://localhost:3003/api';
const OUTPUT = new URL('../src/app/config/api-url.generated.ts', import.meta.url);

// An absolute http(s) URL or a same-origin path, without the trailing slash.
export function normalizeApiUrl(value) {
  const raw = (value ?? '').trim() || DEFAULT_API_URL;
  const url = raw.replace(/\/+$/, '');
  if (url.startsWith('/')) {
    return url;
  }
  const parsed = new URL(url);
  if (!['http:', 'https:'].includes(parsed.protocol)) {
    throw new Error(`API_URL must be http(s) or a path, got "${raw}"`);
  }
  return url;
}

export function renderApiConfig(apiUrl) {
  return `// Generated by scripts/generate-api-config.mjs; do not edit.\nexport const API_URL = ${JSON.stringify(apiUrl)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const apiUrl = normalizeApiUrl(process.env.API_URL);
  writeFileSync(OUTPUT, renderApiConfig(apiUrl));
  console.log(`API_URL=${apiUrl}`);
}
